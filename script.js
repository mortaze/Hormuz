/* ================= INTRO LANGUAGE ================= */

let currentLanguage = "fa";


function setIntroLanguage(lang) {

    const t = translations[lang];

    document.documentElement.lang = lang;

    document.getElementById("introSmall").textContent = t.introSmall;
    document.getElementById("introMain").textContent = t.introMain;
    document.getElementById("introSubtitle").textContent = t.introSubtitle;
    document.getElementById("introScroll").textContent = t.introScroll;
    localStorage.setItem("hormuzLanguage", lang);
}


/* ================= FULL LANGUAGE SWITCH ================= */

function setLanguage(lang) {

    if (!translations[lang]) return;

    currentLanguage = lang;

    const t = translations[lang];

    document.documentElement.lang = lang;

    if (lang === "fa" || lang === "ar") {
        document.documentElement.dir = "rtl";
    } else {
        document.documentElement.dir = "ltr";
    }


    document.querySelectorAll("[data-lang]").forEach(btn => {
        btn.classList.toggle(
            "active",
            btn.dataset.lang === lang
        );
    });


    document.querySelectorAll("[data-i18n]").forEach(element => {

        const key = element.dataset.i18n;

        if (t[key]) {
            element.innerHTML = t[key];
        }

    });

}


